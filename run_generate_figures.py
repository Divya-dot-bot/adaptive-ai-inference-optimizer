def plot_cost_vs_sla(
    dataframe: pd.DataFrame,
) -> None:
    """Create a cost versus SLA violation comparison."""

    plt.figure(
        figsize=(8, 6),
    )

    plt.scatter(
        dataframe["total_cost"],
        dataframe["total_sla_violations"],
        s=120,
    )

    for _, row in dataframe.iterrows():
        plt.annotate(
            row["strategy"],
            (
                row["total_cost"],
                row["total_sla_violations"],
            ),
            xytext=(5, 5),
            textcoords="offset points",
        )

    plt.title(
        "Cost vs Estimated SLA Violations"
    )

    plt.xlabel(
        "Total Simulated Cost"
    )

    plt.ylabel(
        "Total SLA Violations"
    )

    save_figure(
        "cost_vs_sla_violations.png"
    )


def create_summary_table(
    dataframe: pd.DataFrame,
) -> None:
    """Create a clean CSV table for use in the research paper."""

    summary_columns = [
        "strategy",
        "total_cost",
        "average_latency_ms",
        "average_estimated_p95_latency_ms",
        "total_sla_violations",
        "average_active_instances",
        "maximum_active_instances",
        "maximum_queue_length",
        "average_queue_length",
    ]

    summary = dataframe[
        summary_columns
    ].copy()

    output_path = (
        TABLES_DIR
        / "publication_results_table.csv"
    )

    summary.to_csv(
        output_path,
        index=False,
    )

    print(
        f"Saved publication table: {output_path}"
    )


def main() -> None:
    """Generate all experiment figures."""

    print("=" * 70)
    print("ADAPTIVE AI INFERENCE OPTIMIZER")
    print("PUBLICATION FIGURE GENERATION")
    print("=" * 70)

    print("\nLoading exact experiment results...")

    dataframe = load_comparison_results()

    print(
        f"Loaded results for "
        f"{len(dataframe)} strategies."
    )

    print("\nGenerating figures...")

    plot_total_cost(dataframe)

    plot_average_latency(dataframe)

    plot_p95_latency(dataframe)

    plot_sla_violations(dataframe)

    plot_average_instances(dataframe)

    plot_maximum_queue(dataframe)

    plot_cost_vs_sla(dataframe)

    print("\nCreating publication results table...")

    create_summary_table(dataframe)

    print("\n" + "=" * 70)
    print("FIGURE GENERATION COMPLETED SUCCESSFULLY")
    print("=" * 70)

    print(
        "\nIMPORTANT:"
    )

    print(
        "All figures are based on synthetic workloads "
        "and locally simulated AI inference infrastructure."
    )

    print(
        "They must be described as simulation results "
        "in any report or research paper."
    )


if __name__ == "__main__":
    main()