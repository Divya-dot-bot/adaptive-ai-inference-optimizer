"""
Generate publication-ready figures for the
Adaptive AI Inference Optimizer experiment.

Figures are created from the exact results generated by:
    python run_strategy_comparison.py

IMPORTANT:
All figures represent results from a synthetic workload and
locally simulated AI inference infrastructure. They must not be
presented as measurements from real production infrastructure.
"""

from __future__ import annotations

from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd


PROJECT_ROOT = Path(__file__).resolve().parent

COMPARISON_PATH = (
    PROJECT_ROOT
    / "results"
    / "tables"
    / "strategy_comparison.csv"
)

TABLES_DIR = (
    PROJECT_ROOT
    / "results"
    / "tables"
)

FIGURES_DIR = (
    PROJECT_ROOT
    / "results"
    / "figures"
)


def load_comparison_results() -> pd.DataFrame:
    """Load the exact strategy comparison results."""

    if not COMPARISON_PATH.exists():
        raise FileNotFoundError(
            "Strategy comparison results were not found.\n"
            "Run this command first:\n"
            "python run_strategy_comparison.py"
        )

    dataframe = pd.read_csv(COMPARISON_PATH)

    required_columns = [
        "strategy",
        "total_cost",
        "average_latency_ms",
        "average_estimated_p95_latency_ms",
        "total_sla_violations",
        "average_throughput",
        "total_processed_requests",
        "average_active_instances",
        "maximum_active_instances",
        "maximum_queue_length",
        "average_queue_length",
    ]

    missing_columns = [
        column
        for column in required_columns
        if column not in dataframe.columns
    ]

    if missing_columns:
        raise ValueError(
            "Missing required columns: "
            + ", ".join(missing_columns)
        )

    return dataframe


def save_figure(
    filename: str,
) -> None:
    """Save the current Matplotlib figure."""

    FIGURES_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    output_path = FIGURES_DIR / filename

    plt.tight_layout()

    plt.savefig(
        output_path,
        dpi=300,
        bbox_inches="tight",
    )

    print(f"Saved: {output_path}")

    plt.close()


def plot_total_cost(
    dataframe: pd.DataFrame,
) -> None:
    """Plot total simulated infrastructure cost."""

    plt.figure(
        figsize=(8, 5),
    )

    plt.bar(
        dataframe["strategy"],
        dataframe["total_cost"],
    )

    plt.title(
        "Total Simulated Infrastructure Cost"
    )

    plt.xlabel(
        "Autoscaling Strategy"
    )

    plt.ylabel(
        "Total Cost"
    )

    for index, value in enumerate(
        dataframe["total_cost"]
    ):
        plt.text(
            index,
            value,
            f"{value:.2f}",
            ha="center",
            va="bottom",
        )

    save_figure(
        "total_cost_comparison.png"
    )


