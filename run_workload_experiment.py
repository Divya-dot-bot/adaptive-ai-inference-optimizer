"""
Run a synthetic workload generation experiment.

Adaptive AI Inference Optimizer

IMPORTANT:
The workload generated by this script is completely synthetic.
It does not represent real production traffic or measurements from
a real cloud inference-serving system.
"""

from __future__ import annotations

from pathlib import Path

from src.workload import (
    SyntheticWorkloadGenerator,
    WorkloadConfig,
)

def main() -> None:
 """Generate and save a reproducible synthetic AI inference workload."""


print("=" * 70)
print("ADAPTIVE AI INFERENCE OPTIMIZER")
print("Synthetic Workload Experiment")
print("=" * 70)

# Fixed seed ensures reproducible experiments.
config = WorkloadConfig(
    random_seed=42,
    start_time="2026-01-01 00:00:00",
    periods=1440,
    frequency="min",
    baseline_requests=100.0,
)

print("\nCreating synthetic workload generator...")
generator = SyntheticWorkloadGenerator(config)
print("Generating synthetic workload...")
workload = generator.generate()

print("\nWorkload generated successfully.")

print("\nSynthetic workload summary:")
print(f"Total time steps: {len(workload)}")

request_column = "requests"

print(
    f"Average requests/step: "
    f"{workload[request_column].mean():.2f}"
)
print(
    f"Minimum requests/step: "
    f"{workload[request_column].min():.2f}"
)
print(
    f"Maximum requests/step: "
    f"{workload[request_column].max():.2f}"
)
print(
    f"Standard deviation: "
    f"{workload[request_column].std():.2f}"
)

# Create the local generated-data directory if necessary.
output_directory = Path("data/generated")
output_directory.mkdir(
    parents=True,
    exist_ok=True,
)

output_path = (
    output_directory
    / "synthetic_workload.csv"
)

workload.to_csv(
    output_path,
    index=False,
)

print("\nSaved synthetic workload to:")
print(output_path.resolve())

print("\nFirst 5 rows:")
print(workload.head())

print("\nIMPORTANT:")
print(
    "All workload data in this experiment is synthetically generated. "
    "It must not be presented as real production traffic."
)

print("\nExperiment completed successfully.")
print("=" * 70)


if __name__ == "__main__":
 main()
